# Rscript --vanilla inst/validation/report_hrf_noise_recovery.R /tmp/hrf-noise \
#   inst/validation/noise_results
args <- commandArgs(trailingOnly = TRUE)
input <- args[1L]
output <- if (length(args) > 1L) args[2L] else input
dir.create(output, recursive = TRUE, showWarnings = FALSE)
summary <- read.csv(file.path(input, "summary.csv"))
paired <- read.csv(file.path(input, "paired_vs_matched_canonical.csv"))
wide <- reshape(summary[, c("scenario", "method", "lambda", "metric", "mean", "lower", "upper", "n")],
  idvar = c("scenario", "method", "lambda"), timevar = "metric", direction = "wide")
write.csv(wide, file.path(output, "summary.csv"), row.names = FALSE)
wide_pairs <- reshape(paired[, c("scenario", "method", "lambda", "metric", "delta", "lower", "upper", "n")],
  idvar = c("scenario", "method", "lambda"), timevar = "metric", direction = "wide")
write.csv(wide_pairs, file.path(output, "paired_vs_matched_canonical.csv"), row.names = FALSE)
primary <- summary[summary$lambda == .01, ]
scenarios <- unique(primary$scenario); scenarios <- scenarios[scenarios != "null"]
labels <- gsub("_", " ", scenarios)
png(file.path(output, "recovery_comparison.png"), width = 1750, height = 850, res = 145)
par(mfrow = c(1, 3), mar = c(4.5, 1, 3, 1), oma = c(0, 9, 0, 0))
for (metric in c("neural_r", "rpe_r", "rpe_gain_error")) {
  d <- paired[paired$lambda == .01 & paired$metric == metric & paired$method == "gls_calibrated", ]
  d <- d[match(scenarios, d$scenario), ]
  range <- range(c(d$lower, d$upper, 0), finite = TRUE)
  padding <- max(.005, diff(range) * .1)
  plot(NA, xlim = range + c(-padding, padding), ylim = c(.5, length(scenarios) + .5),
    yaxt = "n", ylab = "", xlab = "Change versus matched canonical GLS",
    main = switch(metric, neural_r = "Neural waveform correlation",
      rpe_r = "Onset RPE correlation", rpe_gain_error = "Onset gain absolute error"))
  if (metric == "neural_r") axis(2, at = seq_along(scenarios), labels = labels, las = 1)
  abline(v = 0, col = "grey65", lty = 2)
  segments(d$lower, seq_along(scenarios), d$upper, seq_along(scenarios), col = "#27618e", lwd = 2)
  points(d$delta, seq_along(scenarios), pch = 19, col = "#27618e")
}
invisible(dev.off())
settings <- readRDS(file.path(input, "settings.rds"))
writeLines(c("Generated by inst/validation/report_hrf_noise_recovery.R.",
  paste("Independent datasets per scenario:", settings$repetitions),
  paste("Seed base:", settings$seed_base),
  paste("Reported replicate indices:", paste(range(settings$replicate_indices), collapse = "--")),
  paste("Validation script MD5:", paste(settings$script_md5, collapse = ", ")),
  "Intervals are Monte Carlo t intervals over independent multirun datasets.",
  "Primary lambda is 0.01. Other lambdas are sensitivity analyses, not tuned winners.",
  "Raw per-run/per-dataset results and frozen settings remain in the output directory."),
  file.path(output, "provenance.txt"))
