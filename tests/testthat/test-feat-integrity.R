test_that("validation compares estimated contrast weights and group design values", {
  fit <- make_valid_feat(withr::local_tempdir(), level = 2L)
  spec <- list(design = matrix(1, 4), contrasts = matrix(1))
  feat_save_setup(fit$fsf, fit$syntax, character(), 2L, spec = spec)
  expect_silent(feat_validate_outputs(fit$fsf))
  con <- file.path(fit$fit, "design.con")
  original <- readLines(con)
  writeLines(sub("^1$", "-1", original), con)
  expect_error(feat_validate_outputs(fit$fsf), "contrast weights differ")
  writeLines(original, con)
  mat <- file.path(fit$fit, "design.mat")
  writeLines(sub("^1$", "2", readLines(mat)), mat)
  expect_error(feat_validate_outputs(fit$fsf), "higher-level design differs")
})
