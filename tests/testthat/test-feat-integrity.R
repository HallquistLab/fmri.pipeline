test_that('completion requires a validated current fit and failure takes precedence', {
  root <- withr::local_tempdir()
  fit <- make_valid_feat(root)
  expect_true(get_feat_status(fit$out)$feat_complete)
  file.create(file.path(fit$out, '.feat_fail'))
  expect_false(get_feat_status(fit$out)$feat_complete)
  unlink(file.path(fit$out, '.feat_fail'))
  unlink(file.path(fit$out, '.feat_validated.rds'))
  expect_false(get_feat_status(fit$out)$feat_complete)
  expect_false(get_feat_status(file.path(root, 'absent.gfeat'))$feat_complete)
})

test_that('validation rejects missing, unreadable, nonfinite, and mismatched outputs', {
  root <- withr::local_tempdir()
  fit <- make_valid_feat(root)
  stat <- file.path(fit$fit, 'stats', 'varcope1.nii.gz')
  unlink(stat)
  expect_false(get_feat_status(fit$out)$feat_complete)
  expect_error(fmri.pipeline:::feat_validate_outputs(fit$fsf), 'Missing or ambiguous')
  writeLines('corrupt nifti', stat)
  expect_error(fmri.pipeline:::feat_validate_outputs(fit$fsf))
  RNifti::writeNifti(array(-1, c(3,3,3)), stat)
  expect_error(fmri.pipeline:::feat_validate_outputs(fit$fsf), 'Negative FEAT variance')
  RNifti::writeNifti(array(1, c(2,3,3)), stat)
  expect_error(fmri.pipeline:::feat_validate_outputs(fit$fsf), 'Invalid FEAT statistic')
  RNifti::writeNifti(array(NaN, c(3,3,3)), stat)
  expect_error(fmri.pipeline:::feat_validate_outputs(fit$fsf), 'Invalid FEAT statistic')
  RNifti::writeNifti(array(1, c(3,3,3)), stat)
  con <- file.path(fit$fit, 'design.con')
  writeLines(sub('effect', 'different', readLines(con)), con)
  expect_error(fmri.pipeline:::feat_validate_outputs(fit$fsf), 'do not match setup')
})

test_that('inputs and upstream specifications invalidate every dependent level', {
  root <- withr::local_tempdir()
  event <- file.path(root, 'events.txt'); writeLines('1', event)
  l1 <- make_valid_feat(root, 'l1', inputs = event)
  l2 <- make_valid_feat(root, 'l2', 2L, file.path(l1$fit, 'stats', 'cope1.nii.gz'))
  l3 <- make_valid_feat(root, 'l3', 3L, file.path(l2$fit, 'stats', 'cope1.nii.gz'))
  expect_true(get_feat_status(l3$out)$feat_complete)
  expect_false(fmri.pipeline:::feat_save_setup(l1$fsf, l1$syntax, event, 1L))
  expect_true(get_feat_status(l1$out)$feat_complete)
  writeLines('2', event)
  expect_false(get_feat_status(l1$out)$feat_complete)
  expect_false(get_feat_status(l2$out)$feat_complete)
  expect_false(get_feat_status(l3$out)$feat_complete)
  expect_true(fmri.pipeline:::feat_save_setup(l1$fsf, l1$syntax, event, 1L))
  expect_true(file.exists(file.path(l1$out, '.feat_stale')))
  expect_false(file.exists(file.path(l1$out, '.feat_complete')))
  expect_true(file.exists(file.path(l1$fit, 'stats', 'cope1.nii.gz')))
})

test_that('requested confounds and retained-volume alignment are mandatory', {
  root <- withr::local_tempdir()
  image <- file.path(root, 'input.nii.gz'); RNifti::writeNifti(array(1, c(3,3,3,5)), image)
  validate <- function(n = 5L, conf = NA_character_, requested = FALSE)
    fmri.pipeline:::feat_validate_l1_inputs(image, n, conf, requested)
  expect_silent(validate())
  expect_error(validate(4L), 'image/design volume mismatch')
  expect_error(validate(requested = TRUE), 'Missing requested')
  conf <- file.path(root, 'confounds.txt')
  expect_error(validate(conf = conf, requested = TRUE), 'Missing requested')
  writeLines(as.character(1:4), conf)
  expect_error(validate(conf = conf), 'one row per retained volume')
  writeLines(c('1', '2', 'NA', '4', '5'), conf)
  expect_error(validate(conf = conf), 'finite numeric')
  writeLines(as.character(1:5), conf)
  expect_silent(validate(conf = conf, requested = TRUE))
})

test_that('fresh status prevents stale-queue deletion and keep policies are exclusive', {
  fit <- make_valid_feat(withr::local_tempdir())
  gpa <- make_feat_gpa(fit)
  expect_identical(run_feat_sepjobs(gpa), character())
  expect_true(file.exists(file.path(fit$out, '.feat_complete')))
  file.create(file.path(fit$out, '.feat_fail'))
  gpa$glm_settings$fsl$failed_l1_folder_action <- 'keep'
  expect_identical(run_feat_sepjobs(gpa), character())
  expect_true(file.exists(file.path(fit$out, '.feat_fail')))
  expect_identical(fmri.pipeline:::feat_run_action(get_feat_status(fit$out), 'keep', 'delete'), 'keep')
})

test_that('submission reserves output and defers cleanup until execution', {
  fit <- make_valid_feat(withr::local_tempdir(), name = 'path with spaces')
  gpa <- make_feat_gpa(fit)
  submitted <- NULL
  testthat::local_mocked_bindings(cluster_job_submit = function(batch_file, ...) {
    submitted <<- readLines(batch_file)
    expect_true(dir.exists(fmri.pipeline:::feat_lock_dir(fit$fsf)))
    expect_true(file.exists(file.path(fit$out, '.feat_complete')))
    '1234'
  }, .package = 'fmri.pipeline')
  expect_identical(run_feat_sepjobs(gpa, rerun = TRUE), '1234')
  expect_true(any(grepl("'archive'", submitted, fixed = TRUE)))
  expect_error(run_feat_sepjobs(gpa, rerun = TRUE), 'already queued/running')
  expect_error(fmri.pipeline:::feat_save_setup(fit$fsf, fit$syntax, character(), 1L), 'already queued/running')
  expect_error(fmri.pipeline:::feat_reserve(fit$fsf, 'another'), 'already queued/running')
  fmri.pipeline:::feat_release(fit$fsf, 'wrong-owner')
  expect_true(dir.exists(fmri.pipeline:::feat_lock_dir(fit$fsf)))
})

test_that('failed submission releases reservations without removing outputs', {
  fit <- make_valid_feat(withr::local_tempdir())
  testthat::local_mocked_bindings(cluster_job_submit = function(...) stop('submission failed'), .package = 'fmri.pipeline')
  expect_error(run_feat_sepjobs(make_feat_gpa(fit), rerun = TRUE), 'submission failed')
  expect_false(dir.exists(fmri.pipeline:::feat_lock_dir(fit$fsf)))
  expect_true(get_feat_status(fit$out)$feat_complete)
  expect_identical(fmri.pipeline:::feat_run_action(get_feat_status(fit$out)), 'archive')
  fmri.pipeline:::feat_prepare_run(fit$fsf, 'archive')
  expect_false(dir.exists(fit$out))
  expect_length(list.files(dirname(fit$out), pattern = 'archive_'), 1L)
})

test_that("a late completion marker prevents deletion during worker cleanup", {
