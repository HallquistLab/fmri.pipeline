test_that("FEAT exposes the estimator and outlier settings for the retained attempt", {
  root <- withr::local_tempdir()
  fit <- make_valid_feat(root, level = 3L)
  syntax <- c(fit$syntax, "set fmri(mixed_yn) 1", "set fmri(robust_yn) 1")
  feat_save_setup(fit$fsf, syntax, character(), 3L)
  pending <- get_feat_status(fit$out)
  expect_identical(pending$feat_requested_estimator, "flame12")
  expect_true(pending$feat_requested_outlier_deweighting)
  expect_true(is.na(pending$feat_actual_estimator))

  commands <- sprintf("flameo --ld=stats%04d --runmode=flame12", 0:2)
  writeLines(commands, file.path(fit$fit, ".flame"))
  audit <- file.path(fit$fit, "flame_runner_fallbacks.tsv")
  writeLines(c("ld_dir\tfallback_status", "stats0001\t0"), audit)
  writeLines("Successful retry with robust_yn=0", file.path(fit$out, ".feat_auto_retry_warning"))
  feat_validate_outputs(fit$fsf)
  writeLines(rep("2026-01-01 10:00:00", 2), file.path(fit$out, ".feat_complete"))

  status <- get_feat_status(fit$out)
  expect_true(status$feat_complete)
  expect_identical(status$feat_actual_estimator, "flame12+flame1")
  expect_true(status$feat_requested_outlier_deweighting)
  expect_false(status$feat_actual_outlier_deweighting)
  expect_true(status$feat_auto_retried)
  expect_identical(status$feat_flame1_fallback_count, 1L)
  unlink(audit)
  expect_identical(get_feat_status(fit$out)$feat_actual_estimator, "flame12+flame1")

  setup <- feat_read_setup(fit$fsf)
  expect_true(is.na(feat_estimator_result(setup)$feat_actual_estimator))
  writeLines(c("ld_dir\tfallback_status", "stats0001\t1"), audit)
  expect_true(is.na(feat_estimator_result(setup)$feat_actual_estimator))
  writeLines(c("ld_dir\tfallback_status", sprintf("stats%04d\t0", 0:2)), audit)
  all_slices <- feat_estimator_result(setup)
  expect_identical(all_slices$feat_actual_estimator, "flame1")
  expect_identical(all_slices$feat_flame1_fallback_count, 3L)
  writeLines("ld_dir\tfallback_status", audit)
  writeLines(paste(commands, "--io"), file.path(fit$fit, ".flame"))
  direct <- feat_estimator_result(setup)
  expect_identical(direct$feat_actual_estimator, "flame12")
  expect_true(direct$feat_actual_outlier_deweighting)
  expect_identical(direct$feat_flame1_fallback_count, 0L)

  file.create(file.path(fit$out, ".feat_fail"))
  expect_true(is.na(get_feat_status(fit$out)$feat_actual_estimator))
})
